md = []
md.append("# JRE優待店 完全データベース（品川・川崎・横浜）\n")
md.append("買い物のジャンルから「どの駅ビルに行けばその店があるか」を調べるための一覧です。1店舗が複数のタグを持つことがあります。\n")
import datetime
today = datetime.date.today().isoformat()
md.append(f"※本リストは{today}時点の情報です。店舗の入退店・取扱品は変動するため、最新情報は各施設公式サイトをご確認ください。")
md.append("情報の誤りに気づいた場合は https://github.com/yossato/j/issues までお知らせください。\n")

md.append("## 目次\n")
md.append("- [駅ビル別 店舗一覧](#駅ビル別-店舗一覧)")
md.append("- [タグ別索引（店を探す）](#タグ別索引店を探す)\n")

md.append("## 駅ビル別 店舗一覧\n")
for (station, building) in sorted(by_building.keys()):
    items = by_building[(station, building)]
    md.append(f"### {station}駅 / {building}（{len(items)}店舗）\n")
    md.append("| タグ | 店舗名 | フロア |")
    md.append("|---|---|---|")
    for tags, shop, floor in sorted(items, key=lambda x: (x[1])):
        md.append(f"| {' / '.join(tags)} | {shop} | {floor} |")
    md.append("")

md.append("## タグ別索引（店を探す）\n")
md.append("例：「子供のズボンを買いたい」→「子供服」タグを見る\n")
for tag in sorted(by_tag.keys()):
    items = sorted(set(by_tag[tag]), key=lambda x: (x[1], x[2], x[0]))
    md.append(f"### {tag}（{len(items)}件）\n")
    md.append("| 店舗名 | 駅 | 施設名 | フロア |")
    md.append("|---|---|---|---|")
    for shop, station, building, floor in items:
        md.append(f"| {shop} | {station} | {building} | {floor} |")
    md.append("")

